import mongoose from 'mongoose';
import { CURRENT_ACADEMIC_YEAR } from '../utils/constants.js';

const examScheduleSchema = new mongoose.Schema(
  {
    schoolId: { type: mongoose.Schema.Types.ObjectId, ref: 'School', required: true },
    name: { type: String, required: true }, // e.g., "Mid-Term Examination March 2026"
    type: { type: String }, // unit_test, quiz, midterm, final
    academicYear: { type: String, default: CURRENT_ACADEMIC_YEAR },
    classIds: [{ type: mongoose.Schema.Types.ObjectId, ref: 'Class' }],
    startDate: { type: Date, required: true },
    endDate: { type: Date, required: true },
    sessionType: { type: String, enum: ['morning', 'afternoon', 'both'], default: 'morning' },
    morningSlot: {
      startTime: { type: String, default: '09:00' },
      endTime: { type: String, default: '12:00' },
    },
    afternoonSlot: {
      startTime: { type: String, default: '14:00' },
      endTime: { type: String, default: '17:00' },
    },
    defaultMaxMarks: { type: Number, default: 100 },
    defaultPassingMarks: { type: Number, default: 35 },
    entries: [
      {
        date: { type: Date, required: true },
        session: { type: String, enum: ['morning', 'afternoon'], required: true },
        subjectName: { type: String, required: true },
        classIds: [{ type: mongoose.Schema.Types.ObjectId, ref: 'Class' }],
        maxMarks: { type: Number, default: 100 },
        passingMarks: { type: Number, default: 35 },
        // Per-paper seat map. Generated by POST /exam-schedules/:id/seat
        // (services/examSeating.js). One student per bench by default; when the
        // schedule's seatingOptions.shareBenches is on, double-seater benches may
        // hold two (seatInBench 0/1).
        seating: [
          {
            // Venue the seat belongs to. For a dedicated hall this is the ExamHall
            // id; for a classroom venue it's the Class id (see venueKind).
            hallId: { type: mongoose.Schema.Types.ObjectId },
            hallName: { type: String },
            venueKind: { type: String, enum: ['hall', 'classroom'], default: 'hall' },
            benchIndex: { type: Number }, // 0-based flat index within the venue
            benchCapacity: { type: Number }, // seats of furniture on this bench (1 or 2)
            seatInBench: { type: Number, default: 0 }, // 0 = left/only, 1 = right (shared)
            row: { type: Number },
            col: { type: Number },
            studentId: { type: mongoose.Schema.Types.ObjectId, ref: 'Student' },
            studentName: { type: String },
            classId: { type: mongoose.Schema.Types.ObjectId, ref: 'Class' },
            className: { type: String },
            rollNo: { type: Number },
          },
        ],
      },
    ],

    // Seating configuration + snapshot of the venues used, so the seat map can be
    // re-rendered after a reload without recomputing classroom layouts.
    seatingOptions: {
      shareBenches: { type: Boolean, default: false },
    },
    seatingVenues: [
      {
        venueId: { type: String },
        name: { type: String },
        kind: { type: String, enum: ['hall', 'classroom'], default: 'hall' },
        block: { type: String },
        rows: { type: Number },
        columns: { type: Number },
        benchCapacity: { type: Number },
        capacity: { type: Number },
      },
    ],
    generatedExamIds: [{ type: mongoose.Schema.Types.ObjectId, ref: 'Exam' }],
    status: { type: String, enum: ['draft', 'scheduled', 'sent'], default: 'draft' },
    sentAt: { type: Date },
    sentToParents: { type: Boolean, default: false },
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'Staff' },
    isDeleted: { type: Boolean, default: false, index: true },
    deletedAt: { type: Date },
  },
  { timestamps: true }
);

examScheduleSchema.index({ schoolId: 1, academicYear: 1 });
// Schedule list and overlap guard are both release-critical paths. Keep the
// tenant key first so neither query scans another school's historical data.
examScheduleSchema.index({ schoolId: 1, academicYear: 1, isDeleted: 1, createdAt: -1 });
examScheduleSchema.index({
  schoolId: 1,
  classIds: 1,
  status: 1,
  startDate: 1,
  endDate: 1,
  isDeleted: 1,
});
examScheduleSchema.index(
  { schoolId: 1, name: 1, academicYear: 1 },
  { unique: true, partialFilterExpression: { isDeleted: false } }
);

export default mongoose.model('ExamSchedule', examScheduleSchema);
